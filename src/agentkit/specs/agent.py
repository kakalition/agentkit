"""The ``agent`` spec — a declarative agent that materializes to a live PydanticAI agent.

    from agentkit.specs.agent import AgentDefinition
    from agentkit.specs.registry import SPECS

    spec = AgentDefinition(name="researcher", instructions="Find sources.", memory=True)
    agent = SPECS.materialize("agent", spec)      # a pydantic_ai.Agent
"""

from __future__ import annotations

import re
from collections.abc import Mapping
from typing import Any

from pydantic import Field, field_validator

from agentkit.specs.base import SpecKind, SpecModel
from agentkit.specs.codegen import register_python_renderer
from agentkit.specs.registry import SPECS

__all__ = ["AgentDefinition", "materialize_agent", "render_agent_code", "run_agent"]


class AgentDefinition(SpecModel):
    """A serializable agent definition (the Studio agent-builder payload)."""

    spec_kind = SpecKind.AGENT

    name: str
    instructions: str = ""
    description: str = ""
    model: str | None = None
    tools: list[str] = Field(default_factory=list)
    capabilities: list[str] = Field(default_factory=list)
    posture: str | None = None
    memory: bool = False
    skills: bool = False
    output_type: str = "str"

    @field_validator("name")
    @classmethod
    def _valid_name(cls, value: str) -> str:
        value = (value or "").strip()
        if not value:
            raise ValueError("agent name must not be empty")
        return value


def materialize_agent(
    definition: AgentDefinition,
    *,
    settings: Any = None,
    events: Any = None,
    tools: Mapping[str, Any] | None = None,
    capabilities: Mapping[str, Any] | None = None,
) -> Any:
    """Build a live PydanticAI agent from an :class:`AgentDefinition`.

    ``tools``/``capabilities`` map a declared name to a callable/capability object;
    names not present on the mapping are skipped so a spec can reference tools the
    host wires at run time.
    """
    from agentkit.foundation.agent import Agent

    builder = Agent.make(
        definition.name,
        settings=settings,
        events=events,
        model=definition.model,
        description=definition.description or None,
    )
    if definition.instructions:
        builder.instructions(definition.instructions)
    if definition.posture:
        builder.posture(definition.posture)
    if definition.memory:
        builder.memory()
    if definition.skills:
        builder.skills()
    for name in definition.tools:
        function = (tools or {}).get(name)
        if function is not None:
            builder.tool(function)
    for name in definition.capabilities:
        capability = (capabilities or {}).get(name)
        if capability is None:
            continue
        builder.capability(capability() if callable(capability) else capability)
    builder.output(_output_type(definition.output_type))
    return builder.build(settings=settings, model=definition.model)


def _output_type(name: str) -> Any:
    """Map a declared output type name to a Python type (only ``str`` is built in)."""
    return str if not name or name in {"str", "string", "text"} else str


async def run_agent(
    definition: AgentDefinition,
    prompt: str,
    *,
    settings: Any = None,
    events: Any = None,
    model: Any = None,
    deps: Any = None,
    tools: Mapping[str, Any] | None = None,
    capabilities: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Materialize an agent spec and run one prompt (used by the Studio playground)."""
    agent = materialize_agent(
        definition, settings=settings, events=events, tools=tools, capabilities=capabilities
    )
    result = await agent.run(prompt, deps=deps, model=model)
    return {"agent": definition.name, "output": getattr(result, "output", result)}


def render_agent_code(definition: AgentDefinition) -> str:
    """Generate the class-based Python that rebuilds an agent definition."""
    pascal = "".join(part.capitalize() for part in re.split(r"[^0-9a-zA-Z]+", definition.name) if part) or "Agent"
    lines = [
        f"# Generated by agentkit Studio — agent {definition.name!r}",
        "from agentkit import AgentDefinition",
        "",
        "",
        f"class {pascal}(AgentDefinition):",
        f"    name = {definition.name!r}",
    ]
    if definition.instructions:
        lines.append(f"    instructions = {definition.instructions!r}")
    if definition.posture:
        lines.append(f"    posture = {definition.posture!r}")
    if definition.memory:
        lines.append("    memory = True")
    if definition.skills:
        lines.append("    skills = True")
    for name in definition.tools:
        lines.append(f"    # tools = [{name}]  # wire the {name!r} callable")
    lines.append("    output = str")
    lines.append("")
    lines.append(f"agent = {pascal}.build()")
    return "\n".join(lines) + "\n"


SPECS.register(
    SpecKind.AGENT,
    AgentDefinition,
    materializer=materialize_agent,
    runner=run_agent,
)
register_python_renderer(SpecKind.AGENT, render_agent_code)
