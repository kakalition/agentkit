"""The ``eval`` spec — a declarative evaluation suite.

    from agentkit.specs.eval import EvalDefinition

    spec = EvalDefinition(name="smoke", cases=[{"name": "add", "input": "2+2", "expect": "4"}])
    report = await SPECS.run("eval", spec, target=some_app)
"""

from __future__ import annotations

from typing import Any

from pydantic import Field, field_validator

from agentkit.evals import Case, EvalSuite, Report
from agentkit.specs.base import SpecKind, SpecModel
from agentkit.specs.codegen import register_python_renderer
from agentkit.specs.registry import SPECS

__all__ = ["EvalDefinition", "materialize_eval", "render_eval_code", "run_eval"]


class EvalDefinition(SpecModel):
    """A serializable evaluation definition (dataset ref, graders, criteria)."""

    spec_kind = SpecKind.EVAL

    name: str
    dataset: str | None = None
    graders: list[str] = Field(default_factory=lambda: ["exact"])
    criteria: str = ""
    threshold: float = 1.0
    cases: list[dict[str, Any]] = Field(default_factory=list)

    @field_validator("name")
    @classmethod
    def _valid_name(cls, value: str) -> str:
        value = (value or "").strip()
        if not value:
            raise ValueError("eval name must not be empty")
        return value


def materialize_eval(
    definition: EvalDefinition, *, cases: list[Any] | None = None
) -> EvalSuite:
    """Build an :class:`EvalSuite` from inline cases (or a supplied case list)."""
    resolved = cases
    if resolved is None:
        resolved = [Case.from_dict(case) for case in definition.cases]
    return EvalSuite(resolved, name=definition.name)


async def run_eval(
    definition: EvalDefinition,
    prompt: str = "",
    *,
    target: Any = None,
    cases: list[Any] | None = None,
    model: Any = None,
) -> Report:
    """Run an eval spec against ``target`` (an ``App`` or run callable)."""
    suite = materialize_eval(definition, cases=cases)
    return await suite.run(target, model=model)


def render_eval_code(definition: EvalDefinition) -> str:
    """Generate the Python that rebuilds an eval suite."""
    lines = [
        f"# Generated by agentkit Studio — eval {definition.name!r}",
        "from agentkit.evals import Case, EvalSuite",
        "",
        "suite = EvalSuite([",
    ]
    for case in definition.cases:
        lines.append(f"    Case.from_dict({case!r}),")
    lines.append(f"], name={definition.name!r})")
    lines.append("report = await suite.run(target)")
    return "\n".join(lines) + "\n"


SPECS.register(
    SpecKind.EVAL,
    EvalDefinition,
    materializer=materialize_eval,
    runner=run_eval,
)
register_python_renderer(SpecKind.EVAL, render_eval_code)
