"""Codegen targets — render a spec to ``python``, ``yaml``, or ``json``.

A target is a callable ``spec -> str`` registered under a name. The ``python``
target dispatches on ``spec_kind`` to a kind-specific renderer (registered by each
spec module), falling back to a readable repr for kinds without one. Only
``python``/``yaml``/``json`` are provided (TypeScript is intentionally out of
scope); extensions may register their own via ``manifest.codegen``.
"""

from __future__ import annotations

import pprint
from collections.abc import Callable
from typing import Any

from agentkit.errors import ConfigurationError

__all__ = [
    "CodegenTarget",
    "register_codegen",
    "register_python_renderer",
    "render_spec",
    "targets",
]

CodegenTarget = Callable[[Any], str]

_TARGETS: dict[str, CodegenTarget] = {}
_PYTHON: dict[str, CodegenTarget] = {}


def register_codegen(name: str, renderer: CodegenTarget) -> CodegenTarget:
    """Register (or replace) a codegen target ``name``."""
    _TARGETS[str(name)] = renderer
    return renderer


def register_python_renderer(kind: str, renderer: CodegenTarget) -> CodegenTarget:
    """Register the ``python`` renderer for a spec ``kind``."""
    _PYTHON[str(kind)] = renderer
    return renderer


def targets() -> list[str]:
    return sorted(_TARGETS)


def render_spec(spec: Any, target: str = "python") -> str:
    """Render a spec to ``target`` (``python`` | ``yaml`` | ``json``)."""
    renderer = _TARGETS.get(str(target))
    if renderer is None:
        available = ", ".join(targets()) or "(none)"
        raise ConfigurationError(f"unknown codegen target {target!r}; available: {available}")
    return renderer(spec)


# -- reference targets ---------------------------------------------------


def _render_python(spec: Any) -> str:
    kind = getattr(spec, "spec_kind", "") or ""
    renderer = _PYTHON.get(kind)
    if renderer is not None:
        return renderer(spec)
    return _generic_python(spec)


def _generic_python(spec: Any) -> str:
    kind = getattr(spec, "spec_kind", "") or type(spec).__name__
    name = getattr(spec, "name", "")
    payload = spec.model_dump() if hasattr(spec, "model_dump") else spec
    body = pprint.pformat(payload, sort_dicts=False)
    return (
        f"# Generated by agentkit — {kind} spec {name!r}\n"
        f"# Rebuild it in code, or load the dict with SpecRegistry.validate({kind!r}, spec).\n"
        f"spec = {body}\n"
    )


def _render_yaml(spec: Any) -> str:
    import yaml

    payload = spec.model_dump(mode="json") if hasattr(spec, "model_dump") else spec
    return yaml.safe_dump(payload, sort_keys=False, allow_unicode=True)


def _render_json(spec: Any) -> str:
    if hasattr(spec, "model_dump_json"):
        return spec.model_dump_json(indent=2) + "\n"
    import json

    return json.dumps(spec, indent=2, default=str) + "\n"


register_codegen("python", _render_python)
register_codegen("yaml", _render_yaml)
register_codegen("json", _render_json)
